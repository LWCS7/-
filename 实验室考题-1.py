"""
TCP 服务端（Server）示例程序
------------------------------------------------
作用：
    在本机 127.0.0.1 的 8888 端口上开一个"服务器"，
    等待一个客户端连进来，然后不断接收客户端发来的文字消息并打印。

运行顺序：
    创建 socket → 绑定地址 → 开始监听 → 接受连接
    → 循环收数据 → 关闭连接

注意：
    socket 是"套接字"，可以理解为网络通信的一扇门。
    必须先运行本服务端，再运行客户端，客户端才能连上。
"""

import socket   # 导入 Python 自带的 socket 模块，用于网络通信

# ---------------- 1. 配置参数 ----------------

HOST = "127.0.0.1"
# 服务器监听的 IP 地址。
# 127.0.0.1 是"本机回环地址"(localhost)，表示只允许本机访问，
# 外网/局域网的其他电脑连不上。若想被局域网访问，一般改成 "0.0.0.0"。

PORT = 8888
# 监听的端口号，范围 0~65535。
# 8888 是自己随便选的（常用 8000、8888 等），
# 只要不和系统或其他程序占用的端口冲突即可。

# ---------------- 2. 创建套接字 ----------------

server = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
# socket.socket() 用来创建一个套接字对象，赋值给 server。
# 两个参数：
#   socket.AF_INET      → 使用 IPv4 地址（对应字符串形式的 IP）
#   socket.SOCK_STREAM  → 使用 TCP 协议（可靠、面向连接、有序传输）
# 若想用 UDP，则改成 socket.SOCK_DGRAM。

# ---------------- 3. 绑定地址和端口 ----------------

server.bind((HOST, PORT))
# bind() 把套接字和 (IP, 端口) 绑定起来。
# 注意参数是一个"元组"，所以 IP 和 PORT 外面有一层括号 ((HOST, PORT))。
# 绑定成功后，这个端口就归本程序使用了。

# ---------------- 4. 开始监听 ----------------

server.listen(1)
# listen() 让套接字进入"监听"状态，准备接受客户端连接。
# 参数 1 表示"等待队列"最多允许 1 个还没被处理的连接。
# 如果一次来很多客户端，超出的会被拒绝。

print("服务端已启动，等待连接...")
# 打印提示，让使用者知道程序已经在正常运行、正在等待。

# ---------------- 5. 接受客户端连接 ----------------

conn, addr = server.accept()
# accept() 会"阻塞"（卡住）在这里，直到有客户端连进来。
# 一旦有客户端连接成功，会返回两个值：
#   conn → 一个"新的套接字对象"，专门用来和这个客户端通信
#   addr → 客户端的地址信息，格式是 (IP, 端口) 的元组
# 注意：之后收发数据都用 conn，不再用 server。

print("有客户端连上了！")
# 提示已经有一个客户端连接成功。

# ---------------- 6. 循环接收数据 ----------------

while True:
    # 死循环：不断接收客户端发来的消息，直到客户端断开才退出。

    data = conn.recv(1024)
    # recv(1024) 从客户端接收数据，一次最多接收 1024 字节。
    # 接收到的 data 是"字节(bytes)"类型，不是字符串。
    # 如果客户端还没发数据，这里也会阻塞等待。

    if not data:
        # 如果 data 为空（没有数据），说明客户端已经关闭了连接。
        # 对端正常关闭时，recv 会返回空字节 b""。

        print("客户端断开了")
        break
        # 跳出 while 循环，结束接收。

    print("收到消息：", data.decode("utf-8"))
    # data.decode("utf-8") 把字节数据按 UTF-8 编码解码成可读字符串。
    # 编码/解码必须一致，客户端发送时也要用 UTF-8，
    # 否则中文可能乱码。

# ---------------- 7. 关闭资源 ----------------

conn.close()
# 关闭与客户端的连接套接字，释放资源。

server.close()
# 关闭服务器套接字，彻底释放占用的端口。

# ---------------- 补充说明 ----------------
# 1. 收发数据用的是 conn，不是 server。
# 2. 网络传输的都是 bytes，发送前要 encode，接收后要 decode。
# 3. TCP 是"流式"协议，不保证一次 recv 就收到一条完整消息，
#    消息较长时可能需要循环接收或自定义结束标志。
# 4. 本程序一次只服务一个客户端，服务完就退出。
#    要进一步支持多客户端，可改用循环 accept 或多线程。
