"""
TCP 客户端（Client）示例程序
------------------------------------------------
作用：
    主动连接本机 127.0.0.1 的 8888 端口上的服务端，
    然后不断从键盘输入消息发给服务端，输入 quit 退出。

运行顺序：
    创建 socket → 连接服务端 → 循环输入并发送 → 关闭连接

注意：
    必须先运行服务端，再运行本客户端，否则会连接失败报错。
"""

import socket   # 导入 socket 模块，用于网络通信

# ---------------- 1. 配置参数 ----------------

HOST = "127.0.0.1"
# 要连接的服务端 IP 地址。
# 127.0.0.1 表示"本机"，即连接本机上运行的服务端。
# 如果要连别人的电脑，这里要改成对方的真实 IP。

PORT = 8888
# 要连接的服务端端口，必须和服务端 listen 的端口一致，否则连不上。

# ---------------- 2. 创建套接字 ----------------

client = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
# 创建一个套接字对象，赋值给 client。
#   socket.AF_INET      → IPv4 地址
#   socket.SOCK_STREAM  → TCP 协议
# 必须和服务端使用相同的协议类型，否则无法通信。

# ---------------- 3. 连接服务端 ----------------

client.connect((HOST, PORT))
# connect() 主动发起连接，参数是 (IP, 端口) 元组。
# 这一步会尝试连接服务端：
#   连接成功 → 继续往下执行
#   服务端没开/地址端口错误 → 抛出 ConnectionRefusedError 等异常
# 注意：客户端是"连接方"，用 connect()；
#       服务端是"被连接方"，用 bind() + listen() + accept()。

print("已连接上服务端")
# 连接成功后打印提示。

# ---------------- 4. 循环输入并发送消息 ----------------

while True:
    # 死循环：一直等待用户输入，直到输入 quit 才退出。

    msg = input("输入消息（打 quit 退出）：")
    # input() 从键盘读入一行文字，赋值给 msg。
    # 输入的内容是"字符串(str)"类型。

    if msg.lower() == "quit":
        # msg.lower() 把输入转成小写，再和 "quit" 比较，
        # 这样输入 QUIT、Quit、quit 都能退出。

        break
        # 跳出循环，结束发送。

    client.sendall(msg.encode("utf-8"))
    # sendall() 把数据发给服务端，会确保全部字节都发送出去。
    # msg.encode("utf-8") 把字符串编码成字节(bytes)，
    # 因为网络只能传字节，不能直接传字符串。
    # 编码必须和服务端 decode 用的编码一致，否则中文会乱码。

# ---------------- 5. 关闭连接 ----------------

client.close()
# 关闭套接字，释放资源。
# 关闭后服务端的 recv 会收到空数据，从而知道客户端断开了。

print("已断开")
# 打印提示，程序结束。

# ---------------- 补充说明 ----------------
# 1. 客户端只需 connect，不需要 bind / listen / accept。
# 2. 发送前要 encode，接收时（如果写接收逻辑）要 decode。
# 3. 本示例只发不收。若要收到服务端回复，需加 client.recv(1024)。
# 4. 流程必须是：先启动服务端，再启动客户端。
